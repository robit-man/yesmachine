const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async()=>{
  fs.mkdirSync('artifacts',{recursive:true});
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.YESMACHINE_TEST_URL || 'http://127.0.0.1:21179');
  await page.getByRole('heading',{name:'Your computers. One workspace.'}).waitFor();
  await page.screenshot({path:'artifacts/overview-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Add a computer',exact:true}).click();
  await page.getByRole('button',{name:'Save computer',exact:true}).click();
  await page.getByText('Enter a computer name.',{exact:true}).waitFor();
  assert.equal(await page.locator('#device-name').evaluate(el=>el===document.activeElement),true);
  await page.getByLabel('Computer name',{exact:true}).fill('Browser smoke test');
  await page.getByLabel('IP address or hostname',{exact:true}).fill('192.168.1.250');
  await page.getByRole('button',{name:'Save computer',exact:true}).click();
  await page.locator('#device-dialog').waitFor({state:'hidden'});
  await page.getByRole('link',{name:'Computers',exact:true}).click();
  await page.getByText('Browser smoke test',{exact:true}).waitFor();
  await page.getByLabel('Search computers',{exact:true}).fill('no-such-machine');
  await page.getByRole('heading',{name:'No computers match'}).waitFor();
  await page.getByRole('button',{name:'Clear computer search'}).click();
  await page.getByRole('button',{name:'Pair',exact:true}).click();
  await page.getByLabel('Computer name',{exact:true}).fill('Edited smoke test');
  await page.getByRole('button',{name:'Save computer',exact:true}).click();
  await page.locator('#device-dialog').waitFor({state:'hidden'});
  await page.getByText('Edited smoke test',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Pair',exact:true}).click();
  await page.getByLabel('Computer name',{exact:true}).fill('Discard this edit');
  await page.locator('#device-cancel').click();
  await page.getByRole('button',{name:'Discard changes',exact:true}).click();
  await page.locator('#device-dialog').waitFor({state:'hidden'});
  await page.locator('summary[aria-label="More actions for Edited smoke test"]').click();
  await page.getByRole('button',{name:'Remove computer',exact:true}).click();
  assert.equal(await page.locator('#confirm-cancel').evaluate(el=>el===document.activeElement),true);
  await page.locator('#confirm-accept').click();
  await page.locator('#confirm-dialog').waitFor({state:'hidden'});
  await page.getByRole('heading',{name:'Your other computers go here'}).waitFor();
  await page.getByRole('link',{name:'Network',exact:true}).click();
  await page.getByRole('button',{name:'Enable UPnP access',exact:true}).click();
  await page.getByRole('heading',{name:'Publish this computer through your router?'}).waitFor();
  await page.keyboard.press('Escape');
  await page.locator('#confirm-dialog').waitFor({state:'hidden'});
  await page.screenshot({path:'artifacts/network-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/network-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No horizontal page overflow');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('link',{name:'Capabilities',exact:true}).click();
  await page.getByRole('heading',{name:'Capabilities',exact:true}).waitFor();
  await page.screenshot({path:'artifacts/capabilities-mobile.png',fullPage:true});
  await page.getByRole('link',{name:'Computers',exact:true}).click();
  await page.getByRole('button',{name:'Add computer',exact:true}).click();
  await page.getByLabel('Computer name',{exact:true}).fill('Retained after failure');
  await page.getByLabel('IP address or hostname',{exact:true}).fill('localhost');
  await page.route('**/api/devices/save',route=>route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({error:'Test failure: please retry.'})}));
  await page.getByRole('button',{name:'Save computer',exact:true}).click();
  await page.getByText('Test failure: please retry.',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('Computer name',{exact:true}).inputValue(),'Retained after failure');
  await page.unroute('**/api/devices/save');
  await page.locator('#device-cancel').click();
  await page.getByRole('button',{name:'Discard changes',exact:true}).click();
  assert.deepEqual(errors,[]);
  fs.writeFileSync('artifacts/browser-results.json',JSON.stringify({passed:true,checks:['create','validation','first invalid focus','search','clear','edit','discard','remove','modal focus','UPnP cancel','narrow viewport','reduced motion','failed save preservation'],pageErrors:errors},null,2));
  console.log('Browser smoke passed: CRUD, keyboard, recovery, UPnP dialog, narrow viewport.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
